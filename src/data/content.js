export const SITE_CONTENT_STORAGE_KEY = "walnut_garden_site_content_v1";

// Keep an immutable deep copy of the factory defaults for Reset functionality
export const defaultSiteContent = JSON.parse(JSON.stringify(siteContent));

function applyContentInPlace(target, source) {
  if (!source || typeof source !== "object") return;
  Object.keys(source).forEach((key) => {
    const srcVal = source[key];
    if (Array.isArray(srcVal)) {
      target[key] = JSON.parse(JSON.stringify(srcVal));
    } else if (srcVal && typeof srcVal === "object") {
      if (!target[key] || typeof target[key] !== "object") {
        target[key] = {};
      }
      applyContentInPlace(target[key], srcVal);
    } else if (srcVal !== undefined) {
      target[key] = srcVal;
    }
  });
}

// Hydrate saved admin edits from localStorage on startup
if (typeof window !== "undefined") {
  try {
    const raw = window.localStorage.getItem(SITE_CONTENT_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      applyContentInPlace(siteContent, parsed);
    }
  } catch (err) {
    console.warn("Failed to load saved siteContent from localStorage:", err);
  }
}

export function saveSiteContent(newContent) {
  applyContentInPlace(siteContent, newContent);
  if (typeof window !== "undefined") {
    try {
      window.localStorage.setItem(
        SITE_CONTENT_STORAGE_KEY,
        JSON.stringify(siteContent)
      );
    } catch (err) {
      console.warn("Failed to persist siteContent to localStorage:", err);
    }
    window.dispatchEvent(new CustomEvent("site-content-updated"));
  }
}

export function resetSiteContent() {
  applyContentInPlace(siteContent, defaultSiteContent);
  if (typeof window !== "undefined") {
    try {
      window.localStorage.removeItem(SITE_CONTENT_STORAGE_KEY);
    } catch (err) {
      console.warn("Failed to clear siteContent from localStorage:", err);
    }
    window.dispatchEvent(new CustomEvent("site-content-updated"));
  }
}

